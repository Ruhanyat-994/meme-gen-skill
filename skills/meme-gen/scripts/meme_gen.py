def main(argv=None):
    p = argparse.ArgumentParser(prog="meme_gen.py", description=__doc__.split("\n")[0])
    p.add_argument("--version", action="version", version=__version__)
    sub = p.add_subparsers(dest="cmd", required=True)

    s = sub.add_parser("doctor", help="check Python, Pillow and network access")
    s.set_defaults(fn=cmd_doctor)

    s = sub.add_parser("templates", help="list curated templates (offline); --live lists every template")
    s.add_argument("query", nargs="*", help="filter words, e.g. 'drake' or 'escalating'")
    s.add_argument("--live", action="store_true", help="query the live service for all templates (needs network)")
    s.add_argument("--json", action="store_true")
    s.set_defaults(fn=cmd_templates)

    s = sub.add_parser("url", help="print the image URL (offline)")
