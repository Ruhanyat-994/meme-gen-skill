def cmd_templates(a):
    if a.live:
        data = json.loads(fetch_bytes(f"{BASE_URL}/templates", limit=4 * 1024 * 1024))
        q = [w.lower() for w in (a.query or [])]
        shown = 0
        for t in data:
            hay = " ".join([t.get("id", ""), t.get("name", ""), " ".join(t.get("keywords") or [])]).lower()
            if q and not all(w in hay for w in q):
                continue
            print(f"{t['id']:<24} boxes={t.get('lines', '?')}  {t.get('name', '')}")
            shown += 1
        if not shown:
            print("no match")
        return 0
    q = [w.lower() for w in (a.query or [])]
    rows = []
    for t in load_templates():
        hay = " ".join([t["id"], t["name"], t.get("shape", ""), t.get("hint", ""), " ".join(t.get("tags", []))]).lower()
        if q and not all(w in hay for w in q):
            continue
        rows.append(t)
    if a.json:
        print(json.dumps(rows, indent=2, ensure_ascii=False))
        return 0
    for t in rows:
        print(f"{t['id']:<13} boxes={t['lines']}  [{t['shape']}]  {t['name']}")
        print(f"{'':<13} boxes: {' | '.join(t['roles'])}")
        print(f"{'':<13} use for: {t['hint']}")
        print(f"{'':<13} example: {' / '.join(t['example'])}")
    if not rows:
        print("no match; try fewer words, or `templates --live <words>`")
    return 0


