    if src.lower().startswith(("http://", "https://")):
        if not src.lower().startswith("https://"):
            raise MemeError("the background image URL must be https")
        if a.box or a.style == "bar":
            raise MemeError("--box and --style bar need a local file; for a URL use --top/--bottom")
        lines = [t for t in (a.top, a.bottom) if t] or [""]
        path = "/".join(encode_line(x) for x in lines)
        url = f"{BASE_URL}/images/custom/{path}.png?" + urllib.parse.urlencode({"background": src, "width": str(a.width)})
        print("note: the image service downloads your background URL itself", file=sys.stderr)
        raw = fetch_bytes(url)
        print(save_image(raw, out, stem, overwrite=a.overwrite))
