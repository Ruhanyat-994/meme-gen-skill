#!/usr/bin/env python3
"""meme-gen: make captioned memes from the command line.

Standard library only (Python 3.8+). Pillow is optional: it enables the contact-sheet
`check` command, local-image captioning in `custom`, and re-encoding of downloads.

Commands
  doctor     Check Python, Pillow and network access (run this first)
  templates  List the bundled, curated templates (offline) or the full live list
  url        Print the image URL for a template + text (offline)
  render     Make one meme and save it
  batch      Make many memes from a JSON file; also writes captions.csv + manifest.json
  custom     Put text on your own image (URL, or a local file with Pillow)
  check      Validate every image in a folder and build contact sheets to look at

Images are rendered by the free, open-source memegen.link service. Nothing is
generated by an AI image model, and nothing is uploaded except the caption text.
"""
from __future__ import annotations

import argparse
import csv
import datetime as dt
import io
import json
import os
import re
import sys
import textwrap
import time
import urllib.error
import urllib.parse
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

__version__ = "1.0.0"

DEFAULT_BASE = "https://api.memegen.link"
BASE_URL = os.environ.get("MEME_GEN_BASE_URL", DEFAULT_BASE).rstrip("/")
MAX_BYTES = 12 * 1024 * 1024          # hard cap on any download
MAX_BOX_WORDS = 12                     # style guideline: warn above this
MAX_LINE_CHARS = 200                   # hard cap per text box
TIMEOUT = 25
RETRIES = 2
UA = f"meme-gen/{__version__} (open-source agent skill)"
DATA_FILE = Path(__file__).resolve().parent.parent / "references" / "templates.json"
EXTS = {".png", ".jpg", ".jpeg", ".webp", ".gif"}
_TEMPLATE_ID = re.compile(r"^[a-z0-9][a-z0-9_\-]{0,40}$")


class MemeError(Exception):
    """Any expected, user-facing failure."""


# --------------------------------------------------------------------------- text encoding
# memegen.link path rules: space=_  underscore=__  dash=--  ?=~q  %=~p  #=~h  /=~s  &=~a  newline=~n
_ESC = [("_", "__"), ("-", "--"), (" ", "_"), ("\n", "~n"), ("?", "~q"), ("&", "~a"),
        ("%", "~p"), ("#", "~h"), ("/", "~s"), ("\\", "~b"), ("<", "~l"), (">", "~g"),
        ('"', "''")]


def clean_text(text: str) -> str:
    """Strip control characters and backticks, collapse whitespace, enforce a length cap."""
    text = "".join(ch for ch in str(text) if ch == "\n" or ch >= " ")
    text = text.replace("`", "")
    text = re.sub(r"[ \t]+", " ", text).strip()
    if len(text) > MAX_LINE_CHARS:
        raise MemeError(f"text box is {len(text)} characters (max {MAX_LINE_CHARS}); shorten it")
    return text


def encode_line(text: str) -> str:
    text = clean_text(text)
    if not text:
        return "_"
    for a, b in _ESC:
        text = text.replace(a, b)
    return urllib.parse.quote(text, safe="~_-'$,:.!()*")


def build_url(template: str, lines, width: int = 1080, ext: str = "png", font: str = "") -> str:
    tpl = str(template).strip().lower()
    if not _TEMPLATE_ID.match(tpl):
        raise MemeError(f"bad template id '{template}' (lowercase letters, digits, '-' or '_')")
    if ext not in ("png", "jpg", "webp"):
        raise MemeError("format must be png, jpg or webp")
    if not 100 <= int(width) <= 2000:
        raise MemeError("width must be between 100 and 2000")
    path = "/".join(encode_line(x) for x in (list(lines) or [""]))
    q = {"width": str(int(width))}
    if font:
        q["font"] = font
    return f"{BASE_URL}/images/{urllib.parse.quote(tpl)}/{path}.{ext}?{urllib.parse.urlencode(q)}"


# --------------------------------------------------------------------------- safe network
def _allowed_host() -> str:
    return (urllib.parse.urlparse(BASE_URL).hostname or "").lower()


def check_url(url: str) -> None:
    p = urllib.parse.urlparse(url)
    if p.scheme != "https":
        raise MemeError("blocked: only https is allowed")
    if (p.hostname or "").lower() != _allowed_host():
        raise MemeError(f"blocked: host '{p.hostname}' is not the configured image service '{_allowed_host()}'")
    if p.port not in (None, 443) or p.username or p.password:
        raise MemeError("blocked: unusual port or credentials in URL")


class _StrictRedirect(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        check_url(newurl)  # a redirect may never leave the allowed host
        return super().redirect_request(req, fp, code, msg, headers, newurl)


def fetch_bytes(url: str, limit: int = MAX_BYTES) -> bytes:
    check_url(url)
    opener = urllib.request.build_opener(_StrictRedirect)
    last: Exception | None = None
    for attempt in range(RETRIES + 1):
        try:
            req = urllib.request.Request(url, headers={"User-Agent": UA})
            with opener.open(req, timeout=TIMEOUT) as resp:
                declared = resp.headers.get("Content-Length")
                if declared and declared.isdigit() and int(declared) > limit:
                    raise MemeError(f"blocked: download is {declared} bytes (limit {limit})")
                buf, total = io.BytesIO(), 0
                while True:
                    chunk = resp.read(64 * 1024)
                    if not chunk:
                        break
                    total += len(chunk)
                    if total > limit:
                        raise MemeError(f"blocked: download exceeded {limit} bytes")
                    buf.write(chunk)
                return buf.getvalue()
        except urllib.error.HTTPError as e:
            if e.code in (429, 500, 502, 503, 504) and attempt < RETRIES:
                time.sleep(1.5 * (attempt + 1))
                last = e
                continue
            raise MemeError(_http_help(e.code)) from e
        except urllib.error.URLError as e:
            last = e
            if attempt < RETRIES:
                time.sleep(1.5 * (attempt + 1))
                continue
            raise MemeError(f"network error: {e.reason}. Run `doctor` for help.") from e
    raise MemeError(f"network error: {last}")


def _http_help(code: int) -> str:
    if code in (403, 407):
        return (f"HTTP {code} from {_allowed_host()}: your network or sandbox is blocking it. "
                f"Allow the host '{_allowed_host()}' (HTTPS) in the tool's network/egress settings, then retry.")
    if code == 404:
        return "HTTP 404: unknown template id or bad URL. Run `templates` to see valid ids."
    if code == 414:
        return "HTTP 414: the text is too long for the URL. Shorten the text."
    return f"HTTP {code} from {_allowed_host()}"


# --------------------------------------------------------------------------- image validation
def _kind(raw: bytes):
    if raw.startswith(b"\x89PNG\r\n\x1a\n"):
        return "png"
    if raw.startswith(b"\xff\xd8\xff"):
        return "jpg"
    if raw[:6] in (b"GIF87a", b"GIF89a"):
        return "gif"
    if raw[:4] == b"RIFF" and raw[8:12] == b"WEBP":
        return "webp"
    return None


def _pillow():
    try:
        from PIL import Image  # noqa: F401
        return True
    except ImportError:
        return False


def validate_image(raw: bytes) -> bytes:
    """Reject anything that is not a real image. With Pillow installed, also fully
    decode and re-encode it (drops metadata and any appended bytes)."""
    if not raw:
        raise MemeError("rejected: empty response")
    if _kind(raw) is None:
        raise MemeError("rejected: response is not a PNG/JPEG/GIF/WebP image")
    if not _pillow() or os.environ.get("MEME_GEN_REENCODE", "1") == "0":
        return raw
    from PIL import Image
    Image.MAX_IMAGE_PIXELS = 30_000_000
    try:
        img = Image.open(io.BytesIO(raw))
        img.verify()
        img = Image.open(io.BytesIO(raw))
        img.seek(0)
        img.load()
    except Exception as e:  # corrupt, truncated or hostile
        raise MemeError(f"rejected: image failed to decode ({type(e).__name__})") from e
    out = io.BytesIO()
    kind = _kind(raw)
    if kind == "jpg":
        img.convert("RGB").save(out, "JPEG", quality=93, optimize=True)
    else:
        img.convert("RGBA" if img.mode in ("RGBA", "LA", "P") else "RGB").save(out, "PNG", optimize=True)
    return out.getvalue()


def ext_for(raw: bytes) -> str:
    return {"png": ".png", "jpg": ".jpg", "gif": ".gif", "webp": ".webp"}[_kind(raw) or "png"]


# --------------------------------------------------------------------------- template data
def load_templates() -> list:
    try:
        return json.loads(DATA_FILE.read_text(encoding="utf-8"))["templates"]
    except (OSError, ValueError, KeyError) as e:
        raise MemeError(f"could not read bundled templates at {DATA_FILE}: {e}") from e


def template_map() -> dict:
    return {t["id"]: t for t in load_templates()}


# --------------------------------------------------------------------------- filenames
def slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "meme"


def next_index(out: Path, date: str) -> int:
    best = 0
    if out.is_dir():
        for p in out.iterdir():
            m = re.match(rf"^{re.escape(date)}-(\d+)-", p.name)
            if m:
                best = max(best, int(m.group(1)))
    return best + 1


def unique_path(p: Path) -> Path:
    if not p.exists():
        return p
    for i in range(1, 1000):
        c = p.with_name(f"{p.stem}-{i}{p.suffix}")
        if not c.exists():
            return c
    raise MemeError("too many files with the same name")


# --------------------------------------------------------------------------- spec handling
def normalise_spec(spec: dict, tmap: dict) -> dict:
    """Validate one meme spec: {template, text[], caption?, hashtags?, name?}."""
    if not isinstance(spec, dict):
        raise MemeError("each meme must be an object")
    tpl = str(spec.get("template", "")).strip().lower()
    if not tpl:
        raise MemeError("missing 'template'")
    text = spec.get("text")
    if isinstance(text, str):
        text = [text]
    if not isinstance(text, list) or not text or not all(isinstance(x, str) for x in text):
        raise MemeError(f"'{tpl}': 'text' must be a non-empty list of strings")
    info = tmap.get(tpl)
    warnings = []
    if info is None:
        warnings.append(f"template '{tpl}' is not in the bundled list; trusting the live service")
    else:
        n = int(info["lines"])
        if len(text) > n:
            raise MemeError(f"'{tpl}' has {n} text boxes but {len(text)} were given")
        if len(text) < n:
            warnings.append(f"'{tpl}' has {n} boxes, {len(text)} given (rest left empty)")
            text = list(text) + [""] * (n - len(text))
    for i, t in enumerate(text, 1):
        words = len(t.split())
        if words > MAX_BOX_WORDS:
            warnings.append(f"box {i} has {words} words (aim for 3-8, max {MAX_BOX_WORDS})")
    hashtags = spec.get("hashtags", [])
    if isinstance(hashtags, str):
        hashtags = hashtags.split()
    return {"template": tpl, "text": [clean_text(t) for t in text],
            "caption": str(spec.get("caption", "")).strip(),
            "hashtags": [h if h.startswith("#") else "#" + h for h in hashtags],
            "name": str(spec.get("name", "")).strip(), "warnings": warnings}


def save_image(raw: bytes, out: Path, stem: str, overwrite: bool = False) -> Path:
    clean = validate_image(raw)
    out.mkdir(parents=True, exist_ok=True)
    target = out / (stem + ext_for(clean))
    if not overwrite:
        target = unique_path(target)
    target.write_bytes(clean)
    return target


