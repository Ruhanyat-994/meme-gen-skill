def cmd_render(a):
    spec = normalise_spec({"template": a.template, "text": a.text}, template_map())
    for w in spec["warnings"]:
        print(f"warning: {w}", file=sys.stderr)
    out = Path(a.out)
    raw = fetch_bytes(build_url(spec["template"], spec["text"], a.width, a.format, a.font))
    if a.name:
        stem = Path(a.name).stem
        path = save_image(raw, out, stem, overwrite=a.overwrite)
    else:
        date = dt.date.today().isoformat()
        stem = f"{date}-{next_index(out, date):02d}-{slug(spec['template'])}"
        path = save_image(raw, out, stem)
    print(path)
    return 0


def _load_batch(path: Path) -> list:
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as e:
        raise MemeError(f"cannot read batch file {path}: {e}") from e
    if isinstance(data, dict):
        data = data.get("memes")
    if not isinstance(data, list) or not data:
        raise MemeError("batch file must be a JSON list of memes (or {\"memes\": [...]})")
    if len(data) > 200:
        raise MemeError("batch is limited to 200 memes per run")
    return data


def cmd_batch(a):
    tmap = template_map()
    items = _load_batch(Path(a.file))
    specs, errors = [], []
    for i, raw in enumerate(items, 1):
        try:
            specs.append((i, normalise_spec(raw, tmap)))
        except MemeError as e:
            errors.append((i, str(e)))
    for i, e in errors:
        print(f"ERROR   #{i}: {e}")
    if errors and not a.keep_going:
        print("fix the errors above, or pass --keep-going to render the valid ones")
        return 2
    out = Path(a.out)
    date = dt.date.today().isoformat()
    start = next_index(out, date)
    jobs = []
    for n, (i, spec) in enumerate(specs):
        stem = Path(spec["name"]).stem if spec["name"] else f"{date}-{start + n:02d}-{slug(spec['template'])}"
        jobs.append((i, spec, stem))

    def run(job):
        i, spec, stem = job
        try:
            raw = fetch_bytes(build_url(spec["template"], spec["text"], a.width, a.format, a.font))
            path = save_image(raw, out, stem, overwrite=a.overwrite)
            return (i, spec, path, None)
        except MemeError as e:
            return (i, spec, None, str(e))

    with ThreadPoolExecutor(max_workers=max(1, min(a.jobs, 8))) as ex:
        results = list(ex.map(run, jobs))

    made, failed = [], []
    for i, spec, path, err in results:
        for w in spec["warnings"]:
            print(f"warning #{i}: {w}")
        if err:
            failed.append((i, err))
            print(f"FAILED  #{i} {spec['template']}: {err}")
        else:
            made.append((i, spec, path))
            print(f"OK      #{i} {path.name}")
    if made:
        _write_logs(out, made)
    print(f"\n{len(made)} made, {len(failed)} failed, {len(errors)} invalid -> {out}")
    if made:
        print(f"captions: {out / 'captions.csv'}")
        print("next: run `check` on this folder and look at the contact sheets before you finish")
    return 0 if not failed and not errors else 1


def _write_logs(out: Path, made: list) -> None:
    csv_path = out / "captions.csv"
    exists = csv_path.exists()
    with csv_path.open("a", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        if not exists:
            w.writerow(["file", "template", "text", "caption", "hashtags"])
        for _, spec, path in made:
            w.writerow([path.name, spec["template"], " | ".join(spec["text"]), spec["caption"], " ".join(spec["hashtags"])])
    man_path = out / "manifest.json"
    try:
        manifest = json.loads(man_path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        manifest = []
    for _, spec, path in made:
        manifest.append({"file": path.name, "template": spec["template"], "text": spec["text"],
                         "caption": spec["caption"], "hashtags": spec["hashtags"],
                         "created": dt.datetime.now().isoformat(timespec="seconds")})
    man_path.write_text(json.dumps(manifest, indent=2, ensure_ascii=False), encoding="utf-8")


